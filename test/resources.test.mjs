import assert from 'node:assert/strict';
import './git-fixture.mjs';
import { test } from 'node:test';
import { mkdtempSync, writeFileSync, rmSync, existsSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { NodeJournal } from '../src/node-journal.mjs';
import { nodeResourceStore } from '../src/node-resources.mjs';
import { candidate } from '../src/candidate.mjs';
import { provisionWorktree, finaliseWorktree, retireWorktree, reconcileWorktree } from '../src/resources.mjs';

test('owned worktree finalisation and accepted cleanup survive retries and refuse dirty deletion', async t => {
  const root = mkdtempSync(join(tmpdir(), 'relay-resource-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const repository = join(root, 'repository');
  execFileSync('git', ['init', '-q', repository]);
  writeFileSync(join(repository, 'graph.json'), '{}\n');
  execFileSync('git', ['-C', repository, 'add', '.']);
  execFileSync('git', ['-C', repository, 'commit', '-qm', 'Initial fixture']);
  const journal = new NodeJournal(join(root, 'node.sqlite'), { nodeId: 'node', instanceId: 'backend' });
  t.after(() => journal.close());
  journal.save({ id: 'execution', bindingId: 'worker', state: 'pending', execution: { id: 'execution', runId: 'run', taskId: 'task', state: 'accepted' } });
  const store = nodeResourceStore(journal);
  const config = { key: 'graph-worker', repository, path: join(root, 'worker'), branch: 'graph-worker', bindingId: 'worker' };
  provisionWorktree(store, config);
  provisionWorktree(store, config);
  const old = store.operation(`worktree:${config.key}`);
  delete old.gitDirectory;
  delete old.realPath;
  store.saveOperation(old);
  assert.throws(() => provisionWorktree(store, config), { code: 'resource_conflict' });
  assert.ok(reconcileWorktree(store, { key: config.key }).gitDirectory);
  writeFileSync(join(config.path, 'graph.json'), '{"node":"updated"}\n');
  const snapshot = candidate(config.path);
  journal.save({ ...journal.work('execution'), state: 'native_finished', observation: { outcome: 'succeeded' },
    execution: { ...journal.work('execution').execution, state: 'completed', result: { candidate: snapshot.id, summary: 'Updated graph' } } });
  const input = { key: config.key, runId: 'run', candidate: snapshot.id, message: 'Update graph fixture' };
  const saved = join(root, 'saved-worker');
  renameSync(config.path, saved);
  execFileSync('git', ['clone', '-q', repository, config.path]);
  execFileSync('git', ['-C', config.path, 'checkout', '-q', 'graph-worker']);
  writeFileSync(join(config.path, 'graph.json'), '{"node":"updated"}\n');
  assert.throws(() => finaliseWorktree(store, input), { code: 'resource_conflict' });
  rmSync(config.path, { recursive: true });
  renameSync(saved, config.path);
  const committed = finaliseWorktree(store, input);
  assert.equal(finaliseWorktree(store, input).commit, committed.commit);
  // Simulate crash after Git commit but before recording the receipt.
  store.saveOperation({ ...committed, state: 'intent', commit: undefined });
  assert.equal(finaliseWorktree(store, input).commit, committed.commit);
  assert.equal(execFileSync('git', ['-C', config.path, 'rev-list', '--count', 'HEAD'], { encoding: 'utf8' }).trim(), '2');
  await assert.rejects(retireWorktree(store, input, async () => { throw new Error('Not accepted'); }));
  writeFileSync(join(config.path, 'untracked.txt'), 'keep me');
  await assert.rejects(retireWorktree(store, input, async () => {}), { code: 'dirty_cleanup_blocked' });
  assert.ok(existsSync(config.path));
  rmSync(join(config.path, 'untracked.txt'));
  await retireWorktree(store, input, async () => {});
  await retireWorktree(store, input, async () => {});
  assert.equal(existsSync(config.path), false);
  assert.equal(execFileSync('git', ['-C', repository, 'rev-parse', 'graph-worker'], { encoding: 'utf8' }).trim(), committed.commit);
});
