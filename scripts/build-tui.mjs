// OpenTUI deliberately skips the Solid JSX transform under node_modules.
// Ship precompiled ESM, keeping all renderer/Solid imports on the host runtime.
import { transformSync } from '@babel/core';
import solid from 'babel-preset-solid';
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

for (const [source, target] of [['attachment-sidebar.tsx', 'attachment-sidebar-renderer.mjs'], ['relay-tui.tsx', 'tui.mjs']]) {
  const input = new URL(`../packages/opencode-relay/${source}`, import.meta.url);
  const output = new URL(`../packages/opencode-relay/${target}`, import.meta.url);
  const code = transformSync(readFileSync(input, 'utf8'), { filename: source, configFile: false, babelrc: false,
    presets: [[solid, { generate: 'universal', moduleName: '@opentui/solid' }]],
  }).code.replaceAll('./attachment-sidebar.tsx', './attachment-sidebar-renderer.mjs');
  const contents = `// Generated by scripts/build-tui.mjs. Edit ${source}, not this file.\n${code}\n`;
  if (process.argv.includes('--check')) assert.equal(readFileSync(output, 'utf8'), contents, `Rebuild ${target} with npm run build:tui`);
  else writeFileSync(output, contents);
}
